#ifndef DUMP_MANAGER_INTERFACE_H
#define DUMP_MANAGER_INTERFACE_H

#include "memory_dump/types.h"

/**
 * @file dump_manager_interface.h
 * @brief Интерфейс управляющего модуля дампа.
 *
 * Определяет базовый интерфейс для модулей, выполняющих
 * создание дампа памяти. Служит фасадом для всего процесса,
 * скрывая детали парсинга и выбора стратегии.
 *
 * Позволяет унифицировать взаимодействие с различными
 * реализациями дамп-модулей (например, для разных форматов
 * или методов сжатия).
 */
namespace memory_dump {

/**
 * @brief Интерфейс управляющего модуля.
 *
 * Предоставляет единую точку входа для выполнения операции
 * создания дампа памяти. Реализации инкапсулируют:
 * - Выбор стратегии копирования
 * - Парсинг системных файлов (/proc/iomem)
 * - Обработку ошибок
 * - Формирование выходного файла
 *
 * @note Реализации должны быть идемпотентными (повторный вызов Run()
 *       должен давать одинаковый результат при неизменных условиях)
 */
class IModuleImpl {
public:
    virtual ~IModuleImpl() = default;

    /**
     * @brief Запускает выполнение модуля.
     *
     * Выполняет основную логику модуля:
     * 1. Получает диапазоны физической памяти
     * 2. Выбирает оптимальную стратегию копирования
     * 3. Создает дамп памяти
     * 4. Возвращает результат операции
     *
     * @return ModuleResult
     *         - kSuccess — операция выполнена успешно
     *         - kError — произошла ошибка (недоступен источник,
     *                    ошибка парсинга, ошибка записи и т.д.)
     *
     * @note Реализации должны быть устойчивы к частичным отказам
     * @note При ошибке должны освобождать все захваченные ресурсы
     */
    virtual ModuleResult Run() = 0;
};

} // namespace avml

#endif //DUMP_MANAGER_INTERFACE_H
